#!/usr/bin/env python3
"""Generate the clinical display's 10x20 ASCII bitmap from bundled Roboto Condensed.

Requires Pillow with FreeType support. Run from any directory:
    python3 tools/generate_clinical_font.py
    python3 tools/generate_clinical_font.py --preview /tmp/clinical-font.png

Roboto Condensed is licensed under SIL OFL; see assets/fonts/RobotoCondensed-OFL.txt.
Each glyph keeps a common baseline. Wide glyphs are compressed horizontally to
fit eight columns; a one-pixel side margin prevents neighboring cells touching.
Rows use bit 0 for the leftmost pixel, matching display.c. The output has 95
printable ASCII glyphs (32..126), 20 uint16_t rows each. Pin Pillow/FreeType versions
when reproducing byte-identical generated font files across environments.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT, SCALE = 10, 20, 4


def generate():
    font = ImageFont.truetype(str(ROOT / 'assets/fonts/RobotoCondensed.ttf'), 16 * SCALE)
    font.set_variation_by_axes([700])
    glyphs = []
    for code in range(32, 127):
        image = Image.new('L', (WIDTH, HEIGHT))
        if code != 32:
            left, top, right, bottom = font.getbbox(chr(code), anchor='ls')
            assert top + 15 * SCALE >= SCALE
            assert bottom + 15 * SCALE <= (HEIGHT - 1) * SCALE
            # Render the complete glyph, including negative left bearings.
            source = Image.new('L', (right - left, HEIGHT * SCALE))
            ImageDraw.Draw(source).text((-left, 15 * SCALE), chr(code),
                                       font=font, anchor='ls', fill=255)
            width = min(WIDTH - 2, max(1, round((right - left) / SCALE)))
            source = source.resize((width, HEIGHT), Image.Resampling.LANCZOS)
            image.paste(source, ((WIDTH - width) // 2, 0))
        image = image.point(lambda value: 255 if value >= 112 else 0)
        rows = [sum(1 << x for x in range(WIDTH) if image.getpixel((x, y)))
                for y in range(HEIGHT)]
        assert all(0 <= row < 1 << WIDTH for row in rows)
        if code != 32:
            assert any(rows), chr(code)
        glyphs.append(rows)
    return glyphs


def preview(glyphs, path):
    columns, rows = 16, 6
    sheet = Image.new('RGB', (columns * 14, rows * 25 + 115), '#111820')
    draw = ImageDraw.Draw(sheet)

    def text(x, y, string, color):
        for char in string:
            for yy, bits in enumerate(glyphs[ord(char) - 32]):
                for xx in range(WIDTH):
                    if bits & (1 << xx):
                        draw.point((x + xx, y + yy), color)
            x += WIDTH

    for index in range(95):
        x, y = (index % columns) * 14, (index // columns) * 25
        draw.rectangle((x, y, x + 9, y + 19), fill='#26313b')
        text(x, y, chr(index + 32), 'white')
    for index, line in enumerate(('TCU READY / OFF', 'ECO TRAIL TURBO', '12.5 MPH 100%', 'CAN 300 03 5A 64', 'gypj Q_ ()[]{}')):
        text(2, rows * 25 + index * 22, line, '#b7f6cb')
    path.parent.mkdir(parents=True, exist_ok=True)
    sheet.resize((sheet.width * 4, sheet.height * 4), Image.Resampling.NEAREST).save(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--preview', type=Path, help='Optional glyph sheet; not a firmware asset')
    args = parser.parse_args()
    glyphs = generate()
    lines = [
        '/* Generated by tools/generate_clinical_font.py from assets/fonts/RobotoCondensed.ttf.',
        ' * Roboto Condensed: SIL OFL, see assets/fonts/RobotoCondensed-OFL.txt.',
        ' * ASCII 32..126, 10x20 pixels; bit 0 is the leftmost pixel. */',
        '#include <stdint.h>',
        'static const uint16_t glyphs[95][20] = {'
    ]
    lines.extend('{' + ','.join(f'0x{value:03x}' for value in glyph) + '},' for glyph in glyphs)
    lines.append('};')
    (ROOT / 'firmware/main/font.h').write_text('\n'.join(lines) + '\n')
    if args.preview:
        preview(glyphs, args.preview)
    print('Generated 95 ASCII glyphs, 10x20 pixels, 20 uint16 rows per glyph.')


if __name__ == '__main__':
    main()
